import {
  bluePalette,
  brand,
  brandMark,
  fonts,
  layout,
  lineHeights,
  motion,
  radii,
  softGradient,
  type ThemeColours,
  tagPalette,
  themes,
  toCssVarName,
  typeScale,
} from './tokens'

function themeBlock(colours: ThemeColours, indent: string): string {
  return Object.entries(colours)
    .map(([key, value]) => `${indent}${toCssVarName(key)}: ${value};`)
    .join('\n')
}

/** Renders `tokens.css` from `tokens.ts`. Pure, so the test can compare it with the file. */
export function renderTokensCss(): string {
  const shared = [
    ...Object.entries(brand).map(([step, hex]) => `  --brand-${step}: ${hex};`),
    ...bluePalette.map((hex, i) => `  --blue-${i + 1}: ${hex};`),
    `  --brand-mark: ${brandMark.css};`,
    `  --soft-gradient: ${softGradient.css};`,
    ...tagPalette.map((t) => `  --tag-${t.name}: ${t.hex};`),
    ...Object.entries(typeScale).map(([k, v]) => `  --font-size-${k}: ${v}px;`),
    `  --line-height-ui: ${lineHeights.ui};`,
    `  --line-height-long: ${lineHeights.long};`,
    `  --font-family-sans: ${fonts.sans};`,
    `  --font-family-mono: ${fonts.mono};`,
    ...Object.entries(radii).map(([k, v]) => `  ${toCssVarName(`corner-${k}`)}: ${v}px;`),
    ...Object.entries(layout).map(([k, v]) => `  ${toCssVarName(k)}: ${v}px;`),
    `  --duration-fast: ${motion.fast}ms;`,
    `  --duration-base: ${motion.base}ms;`,
    `  --motion-ease-out: ${motion.easeOut};`,
  ].join('\n')

  return `/* Generated by \`pnpm tokens\` from src/styles/tokens.ts. Do not edit by hand. */

:root {
${shared}
}

:root,
:root[data-theme='light'] {
  color-scheme: light;
${themeBlock(themes.light, '  ')}
}

:root[data-theme='dark'] {
  color-scheme: dark;
${themeBlock(themes.dark, '  ')}
}

@media (prefers-color-scheme: dark) {
  :root[data-theme='system'] {
    color-scheme: dark;
${themeBlock(themes.dark, '    ')}
  }
}
`
}
